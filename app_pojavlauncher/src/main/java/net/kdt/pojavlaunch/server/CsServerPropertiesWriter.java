package net.kdt.pojavlaunch.server;

import java.io.File;
import java.io.FileInputStream;
import java.io.FileOutputStream;
import java.util.Properties;

/**
 * Writes server.properties from CsServerConfig.
 */
public final class CsServerPropertiesWriter {

    private CsServerPropertiesWriter() {}

    /** Create defaults if file missing; otherwise merge config into existing. */
    public static void writeDefaults(File propertiesFile, CsServerConfig config) {
        applyConfig(propertiesFile, config);
    }

    public static void applyConfig(File propertiesFile, CsServerConfig config) {
        Properties props = new Properties();
        if (propertiesFile.exists()) {
            try (FileInputStream in = new FileInputStream(propertiesFile)) {
                props.load(in);
            } catch (Exception ignored) {}
        }

        props.setProperty("server-port", String.valueOf(config.port));
        props.setProperty("server-ip", config.bindAddress != null ? config.bindAddress : "0.0.0.0");
        props.setProperty("motd", config.motd != null ? config.motd : "A Minecraft Server");
        props.setProperty("max-players", String.valueOf(config.maxPlayers));
        props.setProperty("online-mode", String.valueOf(config.onlineMode));
        props.setProperty("white-list", String.valueOf(config.whitelist));
        props.setProperty("difficulty", config.difficulty != null ? config.difficulty : "normal");
        props.setProperty("gamemode", config.gamemode != null ? config.gamemode : "survival");
        props.setProperty("view-distance", String.valueOf(config.viewDistance));
        props.setProperty("simulation-distance", String.valueOf(config.simulationDistance));
        props.setProperty("pvp", String.valueOf(config.pvp));
        props.setProperty("hardcore", String.valueOf(config.hardcore));
        props.setProperty("allow-flight", String.valueOf(config.allowFlight));
        props.setProperty("enable-command-block", String.valueOf(config.enableCommandBlocks));
        props.setProperty("spawn-protection", String.valueOf(config.spawnProtection));
        props.setProperty("level-name", config.worldDir != null ? config.worldDir : "world");
        props.setProperty("enable-status", "true");
        props.setProperty("hide-online-players", "false");

        try {
            File parent = propertiesFile.getParentFile();
            if (parent != null) parent.mkdirs();
            try (FileOutputStream out = new FileOutputStream(propertiesFile)) {
                props.store(out, "Generated by CS Launcher");
            }
        } catch (Exception e) {
            throw new RuntimeException("Failed to write server.properties", e);
        }
    }
}
